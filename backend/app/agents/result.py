"""
app/agents/result.py
~~~~~~~~~~~~~~~~~~~~~
Local, deterministic Final Result component for Nexora.

Turns a VerificationResult and the underlying execution results into a
single AgentResult containing:

- overall success
- execution summary
- final generated report
- verification status
- step counts
- detailed execution results

No tool execution, LLM, external API, or network access is used.
"""

from dataclasses import dataclass

from app.agents.execution import ToolExecutionResult
from app.agents.verification import VerificationResult


# ---------------------------------------------------------------------
# Agent Result
# ---------------------------------------------------------------------


@dataclass
class AgentResult:
    """The final, summarized outcome of a Nexora agent run."""

    success: bool
    summary: str
    steps_completed: int
    steps_failed: int
    execution_results: list[ToolExecutionResult]

    # Final user-facing report generated by the report_generator tool.
    final_report: str = ""

    # Explicit verification status.
    verification_passed: bool = False


# ---------------------------------------------------------------------
# Result Builder
# ---------------------------------------------------------------------


class ResultBuilder:
    """Build the final AgentResult from verification and execution results.

    This component does not execute tools and does not make external
    calls. It only combines and formats information already produced
    by the Nexora pipeline.
    """

    def build(
        self,
        verification: VerificationResult,
        execution_results: list[ToolExecutionResult],
    ) -> AgentResult:
        """Build the final AgentResult for an agent run.

        The final report is extracted from the successful
        `report_generator` execution step.

        If no report_generator step exists, the builder falls back to
        the last successful execution output.
        """

        # -------------------------------------------------------------
        # Build summary
        # -------------------------------------------------------------

        if verification.verified:
            summary = (
                "Nexora completed the task successfully. "
                "All execution steps were verified."
            )
        else:
            summary = (
                "Nexora could not fully complete the task because "
                "one or more execution steps failed."
            )

        # -------------------------------------------------------------
        # Extract final report
        # -------------------------------------------------------------

        final_report = ""

        # Prefer the explicit report_generator result.
        for result in execution_results:
            if (
                result.tool == "report_generator"
                and result.success
            ):
                final_report = result.output
                break

        # -------------------------------------------------------------
        # Fallback
        # -------------------------------------------------------------
        # If a report was not generated, use the last successful
        # execution result so the caller still receives useful output.

        if not final_report:
            successful_results = [
                result
                for result in execution_results
                if result.success
            ]

            if successful_results:
                final_report = successful_results[-1].output

        # -------------------------------------------------------------
        # Return final result
        # -------------------------------------------------------------

        return AgentResult(
            success=verification.verified,
            summary=summary,
            steps_completed=verification.successful_steps,
            steps_failed=verification.failed_steps,
            execution_results=execution_results,
            final_report=final_report,
            verification_passed=verification.verified,
        )